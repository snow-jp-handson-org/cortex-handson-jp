-- 構造化データと属性定義のロード
USE SCHEMA GLACIERSTYLE_DEC_DB.EC_ANALYTICS_SCHEMA;
USE WAREHOUSE GLACIERSTYLE_WH;
COPY INTO PRODUCTS FROM @DATA_STAGE/csv/products.csv FILE_FORMAT = (FORMAT_NAME = CSV_FF) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO CUSTOMERS FROM @DATA_STAGE/csv/customers.csv FILE_FORMAT = (FORMAT_NAME = CSV_FF) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO ORDERS FROM @DATA_STAGE/csv/orders.csv FILE_FORMAT = (FORMAT_NAME = CSV_FF) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RAW_CALL_TRANSCRIPTS FROM @DATA_STAGE/csv/call_transcripts.csv FILE_FORMAT = (FORMAT_NAME = CSV_FF) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO DOCUMENT_ATTRIBUTES FROM @DATA_STAGE/csv/document_attributes.csv FILE_FORMAT = (FORMAT_NAME = CSV_FF) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
SELECT 'PRODUCTS' t, COUNT(*) FROM PRODUCTS UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM CUSTOMERS
UNION ALL SELECT 'ORDERS', COUNT(*) FROM ORDERS UNION ALL SELECT 'CALLS', COUNT(*) FROM RAW_CALL_TRANSCRIPTS
UNION ALL SELECT 'DOC_ATTR', COUNT(*) FROM DOCUMENT_ATTRIBUTES;
