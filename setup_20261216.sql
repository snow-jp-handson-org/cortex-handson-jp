-- 12/16版のセットアップ。旧教材の setup.sql は変更しない。
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS GLACIERSTYLE_WH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE GLACIERSTYLE_WH;
CREATE DATABASE IF NOT EXISTS GLACIERSTYLE_DB;
CREATE SCHEMA IF NOT EXISTS GLACIERSTYLE_DB.EC_ANALYTICS_SCHEMA;
USE SCHEMA GLACIERSTYLE_DB.EC_ANALYTICS_SCHEMA;

CREATE STAGE IF NOT EXISTS DATA_STAGE DIRECTORY = (ENABLE = TRUE)
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
CREATE API INTEGRATION IF NOT EXISTS GLACIERSTYLE_HANDSON_GIT
  API_PROVIDER = git_https_api
  API_ALLOWED_PREFIXES = ('https://github.com/snow-jp-handson-org/') ENABLED = TRUE;
CREATE GIT REPOSITORY IF NOT EXISTS GIT_INTEGRATION_FOR_HANDSON
  API_INTEGRATION = GLACIERSTYLE_HANDSON_GIT
  ORIGIN = 'https://github.com/snow-jp-handson-org/cortex-handson-jp.git';
ALTER GIT REPOSITORY GIT_INTEGRATION_FOR_HANDSON FETCH;
COPY FILES INTO @DATA_STAGE FROM @GIT_INTEGRATION_FOR_HANDSON/branches/pri_20261216/data/
  PATTERN = '(.*/)?((customers|products|orders|call_transcripts)[.]csv|[^/]+[.]pdf|voice_logs/[^/]+[.]mp3)$';
ALTER STAGE DATA_STAGE REFRESH;

CREATE FILE FORMAT IF NOT EXISTS HANDSON_CSV
  TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"';
CREATE TABLE IF NOT EXISTS PRODUCTS (
  product_id VARCHAR, product_name VARCHAR, category_l1 VARCHAR, category_l2 VARCHAR,
  category_l3 VARCHAR, brand VARCHAR, list_price NUMBER, cost_price NUMBER, launch_date DATE);
CREATE TABLE IF NOT EXISTS CUSTOMERS (
  customer_id VARCHAR, last_name VARCHAR, first_name VARCHAR, gender VARCHAR, birth_date DATE,
  email VARCHAR, phone VARCHAR, prefecture VARCHAR, city VARCHAR, registration_date DATE, membership_tier VARCHAR);
CREATE TABLE IF NOT EXISTS ORDERS (
  order_id VARCHAR, order_datetime TIMESTAMP_NTZ, customer_id VARCHAR, product_id VARCHAR,
  quantity NUMBER, unit_price NUMBER, discount_amount NUMBER, total_amount NUMBER,
  order_channel VARCHAR, order_status VARCHAR, lot_no VARCHAR);
CREATE TABLE IF NOT EXISTS RAW_CALL_TRANSCRIPTS (
  call_id VARCHAR, call_datetime TIMESTAMP_NTZ, customer_id VARCHAR, order_id VARCHAR,
  product_id VARCHAR, agent_id VARCHAR, call_duration_sec NUMBER, transcript_text VARCHAR);

COPY INTO PRODUCTS FROM @DATA_STAGE FILES = ('products.csv') FILE_FORMAT = (FORMAT_NAME = HANDSON_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO CUSTOMERS FROM @DATA_STAGE FILES = ('customers.csv') FILE_FORMAT = (FORMAT_NAME = HANDSON_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO ORDERS FROM @DATA_STAGE FILES = ('orders.csv') FILE_FORMAT = (FORMAT_NAME = HANDSON_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RAW_CALL_TRANSCRIPTS FROM @DATA_STAGE FILES = ('call_transcripts.csv') FILE_FORMAT = (FORMAT_NAME = HANDSON_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;